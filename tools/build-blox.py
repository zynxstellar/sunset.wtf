"""Generate Blox Fruits from the existing Rift UI and two movement modules."""
from pathlib import Path
import re
import runpy

ROOT = Path(__file__).resolve().parents[1]

def build():
    menu = runpy.run_path(str(ROOT / 'tools/build-menu-test.py'))['build']()
    ui = menu.split('local source = [========[', 1)[1].split('local firstTab', 1)[0]
    ui = ui.replace('local ENV = ...', 'local ENV = (typeof(getgenv) == "function" and getgenv()) or _G', 1)
    ui = re.sub(r'local SUNSET_BUILD = "[^"]+"', 'local SUNSET_BUILD = "20261011-rift-blox-shared-ui-k377"', ui, count=1)
    imported = (ROOT / 'arsenal-rivals.lua').read_text(encoding='utf-8')
    board = imported.split('function BedWars.BuildUI(boardGame)',1)[1].split('\nif game.PlaceId == 6872265039',1)[0]
    board = 'function BedWars.BuildUI(boardGame)' + board
    start = board.index('    local specs = {')
    end = board.index('    for index = #specs', start)
    board = board[:start] + '''    local specs = {
        { "Movement", "Fly", "Movement", "Blox Fruits", "Fly", "Fly" },
        { "Movement", "Speed", "Movement", "Blox Fruits", "Speed", "Speed" },
    }
''' + board[end:]
    start = board.index('    local descriptions = {')
    end = board.index('    local tooltip =',start)
    board = board[:start] + '    local descriptions = {}\n' + board[end:]
    runtime = (ROOT / 'tools/blox-runtime.luau').read_text(encoding='utf-8')
    tail = '''
Settings.SelectedGame="Blox Fruits"
BedWars={}
''' + board + '''
BedWars.BuildUI("Blox Fruits")
local board=Settings.GameBoards["Blox Fruits"]
Window.Visible=false
board.Visible=true
track(board:GetPropertyChangedSignal("Visible"):Connect(onMenuVisibility))
if ENV.SunsetLoading and ENV.SunsetLoading.Gui then ENV.SunsetLoading.Gui:Destroy() end
ENV.SunsetLoading=nil
Settings.MenuVisibleSnapshot=true
onMenuVisibility()
local watermark=new("TextLabel",{Name="Watermark",AnchorPoint=Vector2.new(0.5,0),
    Position=UDim2.new(0.5,0,0,8),Size=UDim2.fromOffset(330,22),BackgroundTransparency=1,
    Text="RIFT | BLOX FRUITS",Font=T.font,TextSize=14,TextColor3=T.text},Gui)
local function unload()
    restoreMenuInput()
    local abort=ENV.SunsetAbortStartup
    if abort then abort() end
    if ENV.SunsetUnload==unload then ENV.SunsetUnload=nil end
end
ENV.SunsetUnload=unload
print("[RIFT] "..SUNSET_BUILD.." ready. RightShift: menu; Space: up; Ctrl/Shift: down.")
'''
    prefix='''if game.PlaceId ~= 2753915549 and game.GameId ~= 994732206 then return end
if not game:IsLoaded() then game.Loaded:Wait() end
local function isRivalsMode(name) return name=="Blox Fruits" end
'''
    body = prefix + ui + runtime + tail
    return '''-- Generated by tools/build-blox.py from the shared Rift UI.
local source = [========[
''' + body + ''']========]
local chunk,message=loadstring(source,"=RIFT Blox Fruits")
assert(chunk,message)
local ok,failure=pcall(chunk)
if not ok then
    local environment=(typeof(getgenv)=="function" and getgenv()) or _G
    if type(environment.SunsetAbortStartup)=="function" then pcall(environment.SunsetAbortStartup) end
    error("RIFT Blox Fruits startup failed: "..tostring(failure))
end
'''

if __name__ == '__main__':
    (ROOT / 'blox-fruits.lua').write_text(build(),encoding='utf-8',newline='\n')
